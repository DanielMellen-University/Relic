# Generates src/builtins/font8x12.inc: printable ASCII (32..126) as 8x12 bitmaps,
# rendered once from DejaVu Sans Mono (Bitstream Vera license). Rerun only to change the font.
import sys
from PIL import Image, ImageDraw, ImageFont
path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
font = ImageFont.truetype(path, 11)
out = ["// Generated by tools/gen_font.py from DejaVu Sans Mono. 8x12, one byte per row, bit 7 = left.",
       "static const unsigned char kFont8x12[95][12] = {"]
for c in range(32, 127):
    img = Image.new("L", (8, 12), 0)
    ImageDraw.Draw(img).text((1, -1), chr(c), fill=255, font=font)
    rows = []
    for y in range(12):
        b = 0
        for x in range(8):
            if img.getpixel((x, y)) > 110: b |= 0x80 >> x
        rows.append("0x%02x" % b)
    out.append("    {%s},  // %r" % (", ".join(rows), chr(c)))
out.append("};")
open("src/builtins/font8x12.inc", "w").write("\n".join(out) + "\n")
